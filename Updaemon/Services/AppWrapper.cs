using System.Text.RegularExpressions;

namespace Updaemon.Services
{
    /// <summary>
    /// The small <c>/bin/sh</c> script that starts an app: it loads the app's settings and secrets,
    /// then <c>exec</c>s the executable. A command on PATH is one, and a service's unit or plist runs
    /// one, so settings are loaded one way and no secret sits in a unit or plist.
    /// </summary>
    public static partial class AppWrapper
    {
        /// <summary>
        /// The wrapper put on PATH. Anyone may run it, so it loads the secrets only for the user they
        /// belong to (the one the app runs as). For anyone else they are left out: root in particular
        /// must never run lines a service's user could have written into its own secrets file.
        /// </summary>
        public static string ForCommand(string appName, string executablePath, string settingsFilePath, string secretsFilePath) =>
            Render(appName, executablePath, settingsFilePath, $"if [ -O {QuoteShell(secretsFilePath)} ]; then . {QuoteShell(secretsFilePath)}; fi");

        /// <summary>
        /// The wrapper a service starts with. It always runs as the user the secrets belong to, so a
        /// secrets file it cannot read fails the start instead of running the service without them.
        /// </summary>
        public static string ForService(string appName, string executablePath, string settingsFilePath, string secretsFilePath) =>
            Render(appName, executablePath, settingsFilePath, $"if [ -e {QuoteShell(secretsFilePath)} ]; then . {QuoteShell(secretsFilePath)}; fi");

        private static string Render(string appName, string executablePath, string settingsFilePath, string loadSecrets)
        {
            return $"""
                #!/bin/sh
                # Generated by updaemon for app '{appName}'. Changes are overwritten on update.
                set -a
                . {QuoteShell(settingsFilePath)}
                {loadSecrets}
                set +a
                exec {QuoteShell(executablePath)} "$@"

                """;
        }

        /// <summary>
        /// The app a wrapper at <paramref name="path"/> was generated for, or null when nothing is
        /// there or the file is not an updaemon wrapper.
        /// </summary>
        public static string? ReadOwner(string path)
        {
            try
            {
                using (StreamReader reader = new StreamReader(path))
                {
                    if (reader.ReadLine() != "#!/bin/sh")
                    {
                        return null;
                    }

                    Match match = OwnerLineRegex().Match(reader.ReadLine() ?? string.Empty);
                    return match.Success ? match.Groups[1].Value : null;
                }
            }
            catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
            {
                return null;
            }
        }

        /// <summary>Single-quotes a word for /bin/sh.</summary>
        internal static string QuoteShell(string value) => "'" + value.Replace("'", "'\\''") + "'";

        [GeneratedRegex("^# Generated by updaemon for app '([^']+)'\\.")]
        private static partial Regex OwnerLineRegex();
    }
}
