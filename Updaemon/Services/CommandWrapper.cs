using System.Text.RegularExpressions;

namespace Updaemon.Services
{
    /// <summary>
    /// The small <c>/bin/sh</c> script updaemon puts on PATH for a command. It loads the app's
    /// settings, and its secrets when the caller can read them, then runs the executable, so a
    /// command run by hand gets the same settings as the service.
    /// </summary>
    public static partial class CommandWrapper
    {
        public static string Render(string appName, string executablePath, string settingsFilePath, string secretsFilePath)
        {
            return $"""
                #!/bin/sh
                # Generated by updaemon for app '{appName}'. Changes are overwritten on update.
                set -a
                . {QuoteShell(settingsFilePath)}
                if [ -r {QuoteShell(secretsFilePath)} ]; then . {QuoteShell(secretsFilePath)}; fi
                set +a
                exec {QuoteShell(executablePath)} "$@"

                """;
        }

        /// <summary>
        /// The app a wrapper at <paramref name="path"/> was generated for, or null when nothing is
        /// there or the file is not an updaemon wrapper.
        /// </summary>
        public static string? ReadOwner(string path)
        {
            try
            {
                using (StreamReader reader = new StreamReader(path))
                {
                    if (reader.ReadLine() != "#!/bin/sh")
                    {
                        return null;
                    }

                    Match match = OwnerLineRegex().Match(reader.ReadLine() ?? string.Empty);
                    return match.Success ? match.Groups[1].Value : null;
                }
            }
            catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
            {
                return null;
            }
        }

        /// <summary>Single-quotes a word for /bin/sh.</summary>
        internal static string QuoteShell(string value) => "'" + value.Replace("'", "'\\''") + "'";

        [GeneratedRegex("^# Generated by updaemon for app '([^']+)'\\.")]
        private static partial Regex OwnerLineRegex();
    }
}
